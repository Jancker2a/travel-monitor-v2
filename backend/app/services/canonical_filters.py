def resolve_filter_spec(filter_id: Optional[str]) -> Optional[Dict[str, Any]]:
    if not filter_id:
        return None
    key = filter_id.lower().strip()
    if key in CANONICAL_FILTERS:
        return CANONICAL_FILTERS[key]
    key_clean = key.replace("filter_", "")
    for k, spec in CANONICAL_FILTERS.items():
        if k.replace("filter_", "") == key_clean:
            return spec
    return None


