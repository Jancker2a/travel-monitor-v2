async def seed_knowledge():
    logger.info("Starting AI Knowledge Base seeding...")
    
    # 1. Update JSON files
    specs_kb_path = KB_DIR / "hotel_specs_kb.json"
    rep_kb_path = KB_DIR / "hotel_reputation_kb.json"
    
    with open(specs_kb_path, "r", encoding="utf-8") as f:
        specs_data = json.load(f)
    hotels_specs = specs_data.get("hotels", {})
    
    with open(rep_kb_path, "r", encoding="utf-8") as f:
        rep_data = json.load(f)
    hotels_rep = rep_data.get("hotels", {})
    
    for hname, hinfo in HOTEL_DATA.items():
        # Specs KB record
        hotels_specs[hname] = {
            "hotel_name": hname,
            "destination": hinfo["destination"],
            "is_enriched": True,
            "enriched_at": "2026-11-12T08:00:00.000000Z",
            "source": "verified_ai_knowledge",
            "specs": hinfo["specs"],
            "stars": hinfo["stars"]
        }
        # Reputation KB record
        hotels_rep[hname] = {
            "hotel_name": hname,
            "destination": hinfo["destination"],
            "stars": hinfo["stars"],
            "analyzed_at": "2026-11-12T08:00:00.000000Z",
            **hinfo["reputation"]
        }
    
    specs_data["hotels"] = hotels_specs
    rep_data["hotels"] = hotels_rep
    
    with open(specs_kb_path, "w", encoding="utf-8") as f:
        json.dump(specs_data, f, ensure_ascii=False, indent=2)
    logger.info(f"Updated hotel_specs_kb.json ({len(hotels_specs)} hotels total)")
    
    with open(rep_kb_path, "w", encoding="utf-8") as f:
        json.dump(rep_data, f, ensure_ascii=False, indent=2)
    logger.info(f"Updated hotel_reputation_kb.json ({len(hotels_rep)} hotels total)")
    
    # 2. Update PostgreSQL Database
    async with AsyncSessionLocal() as db:
        for hname, hinfo in HOTEL_DATA.items():
            aliases = hinfo.get("aliases", [hname])
            for alias in aliases:
                # Find matching hotels by ID or display_name
                stmt = select(Hotel).where(
                    (Hotel.hotel_id == alias) |
                    (Hotel.display_name == alias) |
                    (Hotel.hotel_id.ilike(f"%{alias}%"))
                )
                res = await db.execute(stmt)
                matched_hotels = res.scalars().all()
                for hotel in matched_hotels:
                    hotel.specs = hinfo["specs"]
                    hotel.reputation = hinfo["reputation"]
                    hotel.stars = hinfo["stars"]
                    hotel.ta_rating = hinfo["ta_rating"]
                    hotel.ta_reviews = hinfo["ta_reviews"]
                    if hinfo.get("region") and not hotel.region:
                        hotel.region = hinfo["region"]
                    if hinfo.get("destination") and not hotel.country:
                        hotel.country = hinfo["destination"]
                    logger.info(f"Updated DB hotel: {hotel.hotel_id} ({hotel.display_name}) -> specs, reputation, stars={hotel.stars}, ta={hotel.ta_rating}")
        
        await db.commit()
    logger.info("Successfully committed all AI knowledge to PostgreSQL!")

if __name__ == "__main__":
    asyncio.run(seed_knowledge())
